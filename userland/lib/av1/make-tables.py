"""Writes the AV1 decoder's constant tables as Pascal include files.

    make-tables.py SPEC_DIRECTORY OUTPUT_DIRECTORY

SPEC_DIRECTORY holds the Markdown sources of the AV1 Bitstream and
Decoding Process Specification (github.com/AOMediaCodec/av1-spec). The
constants (section 3 and the value tables of section 6) and every array
the specification writes out in a code block (scan orders, default CDFs,
filter kernels, quantizer lookups and matrices, ...) are written as Pascal
constants with the specification's names, so the decoder's code can be
compared with the specification line by line. The includes are checked
in; the script is run again only if the specification changes.

Files written:
    Av1.Constants.inc       the integer constants
    Av1.Tables.inc          the arrays that are not CDFs nor quantizer matrices
    Av1.QuantizerMatrices.inc
    Av1.DefaultCdfs.inc     the Default_..._Cdf arrays
    Av1.CdfFields.inc       the fields of TCdfContext (the adaptive CDFs)
    Av1.CdfInitialization.inc  the routines copying defaults into a context
"""

import os
import re
import sys

SPEC_FILES = [
    '03.symbols.md', '06.bitstream.syntax.md', '07.bitstream.semantics.md',
    '08.decoding.process.md', '09.parsing.process.md', '10.additional.tables.md',
]

HEADER = '{ Generated by make-tables.py from the AV1 specification; do not edit. }\n'


def read_spec(directory):
    return {name: open(os.path.join(directory, name), encoding='utf-8').read() for name in SPEC_FILES}


def evaluate(expression, symbols):
    """Evaluates a constant expression of the specification."""
    text = " ".join(expression.replace("\\", "").split())
    for name in sorted(re.findall(r'[A-Za-z_][A-Za-z_0-9]*', text), key=len, reverse=True):
        if name not in symbols:
            raise KeyError(name)
    tokens = re.split(r'([A-Za-z_][A-Za-z_0-9]*)', text)
    resolved = ''.join(str(symbols[t]) if t in symbols else t for t in tokens)
    return int(eval(resolved, {'__builtins__': {}}))


def collect_symbols(sources):
    symbols = {}
    for line in sources['03.symbols.md'].splitlines():
        match = re.match(r'\|\s*`([A-Z][A-Z0-9_]*)`\s*\|\s*([^|]+?)\s*\|', line)
        if match:
            symbols[match.group(1)] = match.group(2)
    resolved = {}
    pending = dict(symbols)
    while pending:
        progress = False
        for name, text in list(pending.items()):
            try:
                resolved[name] = evaluate(text, resolved)
                del pending[name]
                progress = True
            except KeyError:
                pass
        if not progress:
            raise SystemExit('unresolved constants: %s' % pending)
    # The value tables of the semantics: "| 3 | NAME" rows.
    enumerations = {}
    conflicts = set()
    for name in ('06.bitstream.syntax.md', '07.bitstream.semantics.md', '08.decoding.process.md'):
        for line in sources[name].splitlines():
            match = re.match(r'\|\s*(-?\d+)\s*\|\s*([A-Z][A-Z0-9_]+)\s*(\||$)', line)
            if not match:
                # "| lr_type | FrameRestorationType | name": the value is the middle column.
                match = re.match(r'\|\s*-?\d+\s*\|\s*(-?\d+)\s*\|\s*([A-Z][A-Z0-9_]+)\s*$', line)
            if match:
                symbol, value = match.group(2), int(match.group(1))
            else:
                # "| WEDGE_VERTICAL | 1": the name first.
                match = re.match(r'\|\s*([A-Z][A-Z0-9_]+[A-Z0-9])\s*\|\s*(-?\d+)\s*$', line)
                if not match:
                    continue
                symbol, value = match.group(1), int(match.group(2))
            if symbol in resolved:
                continue
            if symbol in enumerations and enumerations[symbol] != value:
                conflicts.add(symbol)
            enumerations[symbol] = value
    for symbol in conflicts:
        del enumerations[symbol]
    resolved.update(enumerations)
    return resolved


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', text)


def collect_tables(sources, symbols):
    tables = {}
    order = []
    lowered_symbols = {s.lower() for s in symbols}
    pattern = re.compile(r'^[ |]*([A-Za-z][A-Za-z_0-9]*)((?:\s*\[[^\]]+\])+)\s*=\s*\n?\s*\{', re.M)
    for file_name in SPEC_FILES:
        text = sources[file_name]
        for match in pattern.finditer(text):
            name = match.group(1)
            if name[0].islower():
                continue    # a local array of a process (tplSamplePos), not a constant table
            dimensions = [evaluate(d, symbols) for d in re.findall(r'\[([^\]]+)\]', match.group(2))]
            start = match.end() - 1
            depth = 0
            position = start
            while True:
                character = text[position]
                if character == '{':
                    depth += 1
                elif character == '}':
                    depth -= 1
                    if depth == 0:
                        break
                position += 1
            body = strip_comments(text[start:position + 1])
            body = re.sub(r'^\s*\|', ' ', body, flags=re.M)
            values = []
            for element in re.split(r'[{},]', body):
                if element.strip():
                    try:
                        values.append(evaluate(element, symbols))
                    except SyntaxError:
                        # A comma missing in the specification (Split_Tx_Size): plain names in a row.
                        words = element.split()
                        if not all(re.match(r'[A-Za-z_0-9]+$', w) for w in words):
                            raise SystemExit('%s: cannot read %r' % (name, element))
                        values.extend(evaluate(w, symbols) for w in words)
                    except KeyError as error:
                        raise SystemExit('%s: unknown value %s' % (name, error))
            count = 1
            for dimension in dimensions:
                count *= dimension
            if count != len(values):
                raise SystemExit('%s: %d values for %s' % (name, len(values), dimensions))
            if name in tables:
                if tables[name] != (dimensions, values):
                    raise SystemExit('%s is given twice with different values' % name)
                continue
            if name.lower() in lowered_symbols:
                name += '_Table'    # Max_Tx_Depth against MAX_TX_DEPTH: Pascal ignores case
            tables[name] = (dimensions, values)
            order.append(name)
    return tables, order


def element_type(values):
    low, high = min(values), max(values)
    if low >= 0 and high <= 255:
        return 'Byte'
    if low >= -128 and high <= 127:
        return 'ShortInt'
    if low >= 0 and high <= 65535:
        return 'Word'
    if low >= -32768 and high <= 32767:
        return 'SmallInt'
    return 'LongInt'


def array_type(dimensions, type_name):
    ranges = ', '.join('0..%d' % (d - 1) for d in dimensions)
    return 'array[%s] of %s' % (ranges, type_name)


def nested_values(dimensions, values, indent):
    if len(dimensions) == 1:
        lines = []
        for offset in range(0, len(values), 16):
            lines.append(', '.join(str(v) for v in values[offset:offset + 16]))
        return '(' + (',\n' + indent + ' ').join(lines) + ')'
    stride = len(values) // dimensions[0]
    parts = [nested_values(dimensions[1:], values[i * stride:(i + 1) * stride], indent + ' ')
             for i in range(dimensions[0])]
    return '(' + (',\n' + indent + ' ').join(parts) + ')'


def write_constant(output, name, dimensions, values, type_name=None):
    if type_name is None:
        type_name = element_type(values)
    output.write('  %s: %s =\n    %s;\n\n' % (name, array_type(dimensions, type_name),
                                           nested_values(dimensions, values, '    ')))


def cdf_field_name(default_name):
    words = default_name[len('Default_'):].split('_')
    return ''.join(w[:1].upper() + w[1:] for w in words)


COEFFICIENT_CDFS = [
    'Default_Txb_Skip_Cdf', 'Default_Eob_Pt_16_Cdf', 'Default_Eob_Pt_32_Cdf', 'Default_Eob_Pt_64_Cdf',
    'Default_Eob_Pt_128_Cdf', 'Default_Eob_Pt_256_Cdf', 'Default_Eob_Pt_512_Cdf', 'Default_Eob_Pt_1024_Cdf',
    'Default_Eob_Extra_Cdf', 'Default_Dc_Sign_Cdf', 'Default_Coeff_Base_Eob_Cdf', 'Default_Coeff_Base_Cdf',
    'Default_Coeff_Br_Cdf',
]
# MvJointCdf[ i ], MvClassCdf[ i ], MvFrCdf[ i ], MvClass0FrCdf[ i ]: one copy per MV context.
MV_CONTEXT_CDFS = ['Default_Mv_Joint_Cdf', 'Default_Mv_Class_Cdf', 'Default_Mv_Fr_Cdf', 'Default_Mv_Class0_Fr_Cdf']
# MvClass0BitCdf[ i ][ comp ] and the like: one copy per MV context and component.
MV_COMPONENT_CDFS = ['Default_Mv_Class0_Bit_Cdf', 'Default_Mv_Class0_Hp_Cdf', 'Default_Mv_Sign_Cdf',
                     'Default_Mv_Bit_Cdf', 'Default_Mv_Hp_Cdf']


def write_cdf_files(directory, tables, order, symbols):
    cdf_names = [n for n in order if n.startswith('Default_') and n.endswith('_Cdf')]
    with open(os.path.join(directory, 'Av1.DefaultCdfs.inc'), 'w') as output:
        output.write(HEADER + '\nconst\n')
        for name in cdf_names:
            dimensions, values = tables[name]
            write_constant(output, name, dimensions, values, 'Word')
    fields = []      # (field, dimensions, inner length)
    copies = []      # Pascal statements of the initializations
    coefficient_copies = []
    mv_contexts = symbols['MV_CONTEXTS']
    for name in cdf_names:
        dimensions, _ = tables[name]
        field = cdf_field_name(name)
        if name == 'Default_Intra_Frame_Y_Mode_Cdf':
            continue    # TileIntraFrameYModeCdf: reset from the default for every tile, never saved
        if name in COEFFICIENT_CDFS:
            shape = dimensions[1:]
            coefficient_copies.append('  Move(%s[Index], Context.%s, SizeOf(Context.%s));' % (name, field, field))
        elif name in MV_CONTEXT_CDFS:
            shape = [mv_contexts] + dimensions
            copies.append('  for Index := 0 to %d do\n    Move(%s, Context.%s[Index], SizeOf(%s));'
                          % (mv_contexts - 1, name, field, name))
        elif name in MV_COMPONENT_CDFS:
            shape = [mv_contexts, 2] + dimensions
            copies.append('  for Index := 0 to %d do\n    for Component := 0 to 1 do\n'
                          '      Move(%s, Context.%s[Index, Component], SizeOf(%s));'
                          % (mv_contexts - 1, name, field, name))
        else:
            shape = dimensions
            copies.append('  Move(%s, Context.%s, SizeOf(%s));' % (name, field, name))
        fields.append((field, shape))
        if name == 'Default_Delta_Lf_Cdf':
            frame_lf_count = symbols['FRAME_LF_COUNT']
            fields.append(('DeltaLfMultiCdf', [frame_lf_count] + dimensions))
            copies.append('  for Index := 0 to %d do\n    Move(%s, Context.DeltaLfMultiCdf[Index], SizeOf(%s));'
                          % (frame_lf_count - 1, name, name))
    with open(os.path.join(directory, 'Av1.CdfFields.inc'), 'w') as output:
        output.write(HEADER)
        for field, shape in fields:
            output.write('    %s: %s;\n' % (field, array_type(shape, 'Word')))
    with open(os.path.join(directory, 'Av1.CdfInitialization.inc'), 'w') as output:
        output.write(HEADER + '\n')
        output.write('procedure InitializeNonCoefficientCdfs(var Context: TCdfContext);\n'
                     'var\n  Index, Component: Integer;\nbegin\n')
        output.write('\n'.join(copies) + '\nend;\n\n')
        output.write('procedure InitializeCoefficientCdfs(var Context: TCdfContext; Index: Integer);\nbegin\n')
        output.write('\n'.join(coefficient_copies) + '\nend;\n\n')
        output.write('procedure ClearCdfCounters(var Context: TCdfContext);\nbegin\n')
        for field, shape in fields:
            count = 1
            for dimension in shape[:-1]:
                count *= dimension
            output.write('  ClearCounters(@Context.%s, %d, %d);\n' % (field, count, shape[-1]))
        output.write('end;\n')


def write_constants(directory, symbols, table_names):
    lowered = {n.lower() for n in table_names}
    with open(os.path.join(directory, 'Av1.Constants.inc'), 'w') as output:
        output.write(HEADER + '\nconst\n')
        for name in sorted(symbols):
            if name.lower() in lowered:
                raise SystemExit('constant %s clashes with a table name' % name)
            output.write('  %s = %d;\n' % (name, symbols[name]))


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    sources = read_spec(sys.argv[1])
    directory = sys.argv[2]
    symbols = collect_symbols(sources)
    tables, order = collect_tables(sources, symbols)
    write_constants(directory, symbols, order)
    write_cdf_files(directory, tables, order, symbols)
    with open(os.path.join(directory, 'Av1.Tables.inc'), 'w') as output:
        output.write(HEADER + '\nconst\n')
        for name in order:
            if (name.startswith('Default_') and name.endswith('_Cdf')) or name == 'Quantizer_Matrix':
                continue
            dimensions, values = tables[name]
            # Scan orders all Word, so that one pointer type walks any of them.
            write_constant(output, name, dimensions, values, 'Word' if '_Scan_' in name else None)
    with open(os.path.join(directory, 'Av1.QuantizerMatrices.inc'), 'w') as output:
        output.write(HEADER + '\nconst\n')
        dimensions, values = tables['Quantizer_Matrix']
        write_constant(output, 'Quantizer_Matrix', dimensions, values)
    print('%d constants, %d tables' % (len(symbols), len(order)))


if __name__ == '__main__':
    main()
