"""Writes libweb's generated tables (at build time) from the data files in
userland/lib/web/data:

    Web.Atoms.WellKnown.inc           the predeclared atoms (well-known-names.txt)
    Web.Encoding.Table.inc            the encodings, their names and labels
                                      (encoding-labels.txt)
    Web.Encoding.SingleByteTables.inc the single-byte indexes (single-byte-indexes.txt)
    Web.Html.NamedReferenceTable.inc  the named character references
                                      (named-character-references.txt)

    python3 userland/lib/web/make-tables.py <output directory>
"""

import os
import re
import sys

DATA_DIRECTORY = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data')


def data_lines(name):
    with open(os.path.join(DATA_DIRECTORY, name), encoding='utf-8') as data_file:
        for line in data_file:
            line = line.rstrip('\n')
            if line.strip() == '' or line.lstrip().startswith('#'):
                continue
            yield line


def pascal_string(text):
    """A Pascal string expression for text (UTF-8), split into short pieces."""
    pieces = []
    current = ''
    for byte in text.encode('utf-8'):
        if 32 <= byte < 127 and byte != 39:
            if current.endswith("'") or current == '':
                current = current[:-1] if current.endswith("'") else current + "'"
                current += chr(byte) + "'"
            else:
                current += "'" + chr(byte) + "'"
        else:
            current += '#%d' % byte
        if len(current) > 90:
            pieces.append(current)
            current = ''
    if current:
        pieces.append(current)
    if not pieces:
        return "''"
    return ' +\n    '.join(pieces)


def identifier_for(name):
    parts = re.split(r'[^A-Za-z0-9]+', name)
    return 'Atom' + ''.join(part[:1].upper() + part[1:] for part in parts if part)


def write_atoms(output):
    names = []
    identifiers = {}
    seen = set()
    for line in data_lines('well-known-names.txt'):
        if '=' in line and ' ' not in line.strip():
            identifier, name = line.strip().split('=', 1)
            entries = [(identifier, name)]
        else:
            entries = [(None, name) for name in line.split()]
        for identifier, name in entries:
            if name in seen:
                continue
            seen.add(name)
            identifier = identifier or identifier_for(name)
            key = identifier.lower()
            if key in identifiers:
                sys.exit('make-tables.py: %s and %s both make %s' % (identifiers[key], name, identifier))
            identifiers[key] = name
            names.append((identifier, name))
    with open(os.path.join(output, 'Web.Atoms.WellKnown.inc'), 'w') as out:
        out.write('{ Generated by make-tables.py from data/well-known-names.txt. }\n\nconst\n')
        for index, (identifier, name) in enumerate(names, 1):
            out.write('  %s = %d;\n' % (identifier, index))
        out.write('  WellKnownAtomCount = %d;\n\n' % len(names))
        out.write('  WellKnownAtomNames: array[1..WellKnownAtomCount] of string = (\n')
        out.write(',\n'.join('    ' + pascal_string(name) for _, name in names))
        out.write('\n  );\n')


ENCODING_IDENTIFIERS = {
    'UTF-8': 'Utf8', 'IBM866': 'Ibm866', 'ISO-8859-8-I': 'Iso8859_8I', 'KOI8-R': 'Koi8R', 'KOI8-U': 'Koi8U',
    'macintosh': 'Macintosh', 'x-mac-cyrillic': 'XMacCyrillic', 'GBK': 'Gbk', 'gb18030': 'Gb18030', 'Big5': 'Big5',
    'EUC-JP': 'EucJp', 'ISO-2022-JP': 'Iso2022Jp', 'Shift_JIS': 'ShiftJis', 'EUC-KR': 'EucKr',
    'replacement': 'Replacement', 'UTF-16BE': 'Utf16Be', 'UTF-16LE': 'Utf16Le', 'x-user-defined': 'XUserDefined',
}


def encoding_identifier(name):
    if name in ENCODING_IDENTIFIERS:
        suffix = ENCODING_IDENTIFIERS[name]
    elif name.startswith('ISO-8859-'):
        suffix = 'Iso8859_' + name[len('ISO-8859-'):]
    elif name.startswith('windows-'):
        suffix = 'Windows' + name[len('windows-'):]
    else:
        sys.exit('make-tables.py: no identifier for encoding %s' % name)
    return 'TextEncoding' + suffix


def read_encodings():
    encodings = []
    labels = []
    for line in data_lines('encoding-labels.txt'):
        if line.endswith(':') and not line.startswith(' '):
            encodings.append(line[:-1])
        else:
            for label in line.split():
                labels.append((label, encodings[-1]))
    return encodings, labels


def read_single_byte_indexes():
    indexes = {}
    current = None
    for line in data_lines('single-byte-indexes.txt'):
        fields = line.split()
        if len(fields) == 1 and not re.fullmatch(r'[0-9A-F]{4}', fields[0]):
            current = fields[0]
            indexes[current] = []
        else:
            indexes[current].extend(int(field, 16) for field in fields)
    for name, values in indexes.items():
        if len(values) != 128:
            sys.exit('make-tables.py: the index of %s has %d entries' % (name, len(values)))
    return indexes


def write_encodings(output):
    encodings, labels = read_encodings()
    indexes = read_single_byte_indexes()
    index_names = list(indexes)
    with open(os.path.join(output, 'Web.Encoding.Table.inc'), 'w') as out:
        out.write('{ Generated by make-tables.py from data/encoding-labels.txt. }\n\ntype\n')
        out.write('  TTextEncoding = (\n')
        out.write(',\n'.join('    ' + encoding_identifier(name) for name in encodings))
        out.write('\n  );\n\n')
        out.write('  TEncodingLabel = record\n    Name: string;\n    Encoding: TTextEncoding;\n  end;\n\nconst\n')
        out.write('  TextEncodingNames: array[TTextEncoding] of string = (\n')
        out.write(',\n'.join("    '%s'" % name for name in encodings))
        out.write('\n  );\n\n')
        labels.sort()
        out.write('  EncodingLabelCount = %d;\n' % len(labels))
        out.write('  EncodingLabels: array[0..EncodingLabelCount - 1] of TEncodingLabel = (\n')
        out.write(',\n'.join("    (Name: '%s'; Encoding: %s)" % (label, encoding_identifier(name))
                             for label, name in labels))
        out.write('\n  );\n\n')
        out.write('  { The single-byte index each encoding decodes with, or -1. }\n')
        out.write('  SingleByteIndexOf: array[TTextEncoding] of ShortInt = (\n')
        rows = []
        for name in encodings:
            index_name = 'ISO-8859-8' if name == 'ISO-8859-8-I' else name
            rows.append('    %d' % (index_names.index(index_name) if index_name in indexes else -1))
        out.write(',\n'.join(rows))
        out.write('\n  );\n')
    with open(os.path.join(output, 'Web.Encoding.SingleByteTables.inc'), 'w') as out:
        out.write('{ Generated by make-tables.py from data/single-byte-indexes.txt. }\n\nconst\n')
        out.write('  SingleByteIndexCount = %d;\n' % len(index_names))
        out.write('  SingleByteIndexes: array[0..SingleByteIndexCount - 1, 0..127] of Word = (\n')
        blocks = []
        for name in index_names:
            values = indexes[name]
            lines = ['      ' + ', '.join('$%04X' % value for value in values[row * 16:row * 16 + 16])
                     for row in range(8)]
            blocks.append('    { %s }\n    (\n%s\n    )' % (name, ',\n'.join(lines)))
        out.write(',\n'.join(blocks))
        out.write('\n  );\n')


def write_named_references(output):
    entries = []
    for line in data_lines('named-character-references.txt'):
        fields = line.split()
        entries.append((fields[0], [int(field, 16) for field in fields[1:]]))
    entries.sort(key=lambda entry: entry[0].encode('ascii'))
    name_data = ''.join(name for name, _ in entries)
    if len(name_data) > 65535:
        sys.exit('make-tables.py: the names no longer fit Word offsets')
    with open(os.path.join(output, 'Web.Html.NamedReferenceTable.inc'), 'w') as out:
        out.write('{ Generated by make-tables.py from data/named-character-references.txt. }\n\nconst\n')
        out.write('  NamedReferenceCount = %d;\n' % len(entries))
        out.write('  NamedReferenceLongestName = %d;\n' % max(len(name) for name, _ in entries))
        out.write('  NamedReferenceNameData: string =\n    %s;\n\n' % pascal_string(name_data))
        out.write('  NamedReferences: array[0..NamedReferenceCount - 1] of TNamedReference = (\n')
        rows = []
        offset = 0
        for name, code_points in entries:
            if len(code_points) > 2 or (len(code_points) == 2 and code_points[1] > 0xFFFF):
                sys.exit('make-tables.py: %s does not fit the table' % name)
            second = code_points[1] if len(code_points) == 2 else 0
            rows.append('    (NameOffset: %d; NameLength: %d; FirstCodePoint: $%X; SecondCodePoint: $%X)'
                        % (offset, len(name), code_points[0], second))
            offset += len(name)
        out.write(',\n'.join(rows))
        out.write('\n  );\n')


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: make-tables.py <output directory>')
    output = sys.argv[1]
    os.makedirs(output, exist_ok=True)
    write_atoms(output)
    write_encodings(output)
    write_named_references(output)


if __name__ == '__main__':
    main()
